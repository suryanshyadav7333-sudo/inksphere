-- Replace YOUR_ADMIN_EMAIL@example.com in every policy below with the owner's exact email.
create table if not exists public.blog_posts (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'Ideas',
  excerpt text not null,
  content text not null,
  cover_url text,
  read_time text not null default '3 min read',
  published boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.blog_posts enable row level security;

-- Public visitors can only read posts that are published.
drop policy if exists "Anyone can read published blogs" on public.blog_posts;
create policy "Anyone can read published blogs"
on public.blog_posts for select
using (published = true);

-- Only the chosen owner can publish.
drop policy if exists "Only owner can insert blogs" on public.blog_posts;
create policy "Only owner can insert blogs"
on public.blog_posts for insert to authenticated
with check ((auth.jwt() ->> 'email') = 'YOUR_ADMIN_EMAIL@example.com');

-- Only the chosen owner can edit posts.
drop policy if exists "Only owner can update blogs" on public.blog_posts;
create policy "Only owner can update blogs"
on public.blog_posts for update to authenticated
using ((auth.jwt() ->> 'email') = 'YOUR_ADMIN_EMAIL@example.com')
with check ((auth.jwt() ->> 'email') = 'YOUR_ADMIN_EMAIL@example.com');

-- Only the chosen owner can delete posts.
drop policy if exists "Only owner can delete blogs" on public.blog_posts;
create policy "Only owner can delete blogs"
on public.blog_posts for delete to authenticated
using ((auth.jwt() ->> 'email') = 'YOUR_ADMIN_EMAIL@example.com');
